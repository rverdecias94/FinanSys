-- Recurrentes (Fase 7 del roadmap contable, solo la parte de plantillas).
-- Plantillas de ingresos/gastos que se materializan como transactions al abrir
-- Finanzas (RPC generate_due_recurring_transactions) o al pulsar "Registrar ahora".
-- Idempotente. Respeta period_locks y el límite mensual del plan (triggers existentes).

create table if not exists public.recurring_transactions (
  id              bigint generated by default as identity primary key,
  user_id         uuid not null default get_current_business_id() references auth.users(id),
  type            text not null check (type in ('income', 'expense')),
  amount          numeric not null check (amount > 0),
  currency        text not null,
  category        text not null,
  description     text not null,
  payment_method  text,
  contact_id      bigint references public.contacts(id) on delete set null,
  status          text not null default 'paid' check (status in ('paid', 'pending')),
  frequency       text not null check (frequency in ('weekly', 'biweekly', 'monthly', 'yearly')),
  next_run        date not null,
  end_date        date,
  is_active       boolean not null default true,
  last_generated_at timestamptz,
  notes           text,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

create index if not exists recurring_transactions_user_idx
  on public.recurring_transactions (user_id);

create index if not exists recurring_transactions_due_idx
  on public.recurring_transactions (user_id, is_active, next_run)
  where is_active = true;

alter table public.recurring_transactions enable row level security;

drop policy if exists recurring_transactions_read on public.recurring_transactions;
create policy recurring_transactions_read on public.recurring_transactions
  for select using (has_permission_secure(user_id, 'finanzas.view'));

drop policy if exists recurring_transactions_insert on public.recurring_transactions;
create policy recurring_transactions_insert on public.recurring_transactions
  for insert with check (
    (user_id = get_current_business_id())
    and has_permission_secure(user_id, 'finanzas.create')
  );

drop policy if exists recurring_transactions_update on public.recurring_transactions;
create policy recurring_transactions_update on public.recurring_transactions
  for update
  using (has_permission_secure(user_id, 'finanzas.edit'))
  with check (has_permission_secure(user_id, 'finanzas.edit'));

drop policy if exists recurring_transactions_delete on public.recurring_transactions;
create policy recurring_transactions_delete on public.recurring_transactions
  for delete using (has_permission_secure(user_id, 'finanzas.delete'));

grant select, insert, update, delete on public.recurring_transactions to authenticated;
grant usage, select on sequence public.recurring_transactions_id_seq to authenticated;

-- Avanza la fecha según frecuencia (meses/años usan aritmética de calendario).
create or replace function public.advance_recurring_date(p_date date, p_frequency text)
returns date
language sql
immutable
set search_path to 'public', 'pg_temp'
as $$
  select case p_frequency
    when 'weekly'   then (p_date + interval '7 days')::date
    when 'biweekly' then (p_date + interval '14 days')::date
    when 'monthly'  then (p_date + interval '1 month')::date
    when 'yearly'   then (p_date + interval '1 year')::date
    else p_date
  end;
$$;

revoke all on function public.advance_recurring_date(date, text) from public;
grant execute on function public.advance_recurring_date(date, text) to authenticated;

-- Materializa UNA ocurrencia: inserta la transaction y avanza next_run.
-- p_force_today: si true, usa current_date como fecha del movimiento (Registrar ahora).
create or replace function public._materialize_recurring(
  p_row public.recurring_transactions,
  p_force_today boolean default false
)
returns bigint
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_run date := case when p_force_today then current_date else p_row.next_run end;
  v_lock date;
  v_tx_id bigint;
  v_paid numeric;
  v_next date;
  v_fx numeric;
begin
  if not p_row.is_active then
    return null;
  end if;

  if p_row.end_date is not null and v_run > p_row.end_date then
    update public.recurring_transactions
      set is_active = false, updated_at = now()
      where id = p_row.id;
    return null;
  end if;

  -- Si cae en período cerrado, solo avanzamos la plantilla (no inventamos pasado).
  select closed_through into v_lock
  from public.period_locks
  where user_id = p_row.user_id;

  if v_lock is not null and v_run <= v_lock then
    v_next := public.advance_recurring_date(v_run, p_row.frequency);
    update public.recurring_transactions
      set next_run = v_next,
          updated_at = now(),
          is_active = case
            when end_date is not null and v_next > end_date then false
            else is_active
          end
      where id = p_row.id;
    return null;
  end if;

  -- Idempotencia: no duplicar la misma plantilla + misma fecha de corrida.
  if exists (
    select 1
    from public.transactions t
    where t.user_id = p_row.user_id
      and (t.details->>'recurring_id') = p_row.id::text
      and (t.details->>'recurring_run') = v_run::text
  ) then
    if p_force_today and p_row.next_run > current_date then
      return null;
    end if;
    v_next := public.advance_recurring_date(greatest(p_row.next_run, v_run), p_row.frequency);
    update public.recurring_transactions
      set next_run = case when p_row.next_run <= v_run then v_next else p_row.next_run end,
          last_generated_at = coalesce(last_generated_at, now()),
          updated_at = now()
      where id = p_row.id;
    return null;
  end if;

  v_paid := case when p_row.status = 'paid' then p_row.amount else 0 end;

  -- Tasa opcional (misma idea que el cliente): no bloquea si falta.
  select er.units_per_base into v_fx
  from public.exchange_rates er
  where er.user_id = p_row.user_id
    and er.currency_code = p_row.currency
    and er.effective_date <= v_run
  order by er.effective_date desc
  limit 1;

  insert into public.transactions (
    user_id, date, amount, currency, category, description, type,
    contact_id, status, due_date, paid_amount, fx_units_per_base, details
  ) values (
    p_row.user_id,
    v_run::timestamptz,
    p_row.amount,
    p_row.currency,
    p_row.category,
    p_row.description,
    p_row.type,
    p_row.contact_id,
    p_row.status,
    case when p_row.status = 'paid' then null else v_run::timestamptz end,
    v_paid,
    v_fx,
    jsonb_build_object(
      'payment_method', p_row.payment_method,
      'notes', p_row.notes,
      'recurring_id', p_row.id,
      'recurring_run', v_run::text,
      'attachments', '[]'::jsonb
    )
  )
  returning id into v_tx_id;

  -- "Registrar ahora" con fecha futura adelanta y consume esa ocurrencia.
  if p_force_today and p_row.next_run > current_date then
    v_next := public.advance_recurring_date(p_row.next_run, p_row.frequency);
  else
    v_next := public.advance_recurring_date(v_run, p_row.frequency);
  end if;

  update public.recurring_transactions
    set next_run = v_next,
        last_generated_at = now(),
        updated_at = now(),
        is_active = case
          when end_date is not null and v_next > end_date then false
          else is_active
        end
    where id = p_row.id;

  return v_tx_id;
end;
$$;

revoke all on function public._materialize_recurring(public.recurring_transactions, boolean) from public;

-- Genera todos los vencidos del negocio actual (máx. 24 por plantilla por llamada).
create or replace function public.generate_due_recurring_transactions()
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_business uuid := public.get_current_business_id();
  r public.recurring_transactions;
  v_created int := 0;
  v_skipped int := 0;
  v_limit_hit boolean := false;
  v_tx bigint;
  v_guard int;
begin
  if v_business is null or auth.uid() is null then
    raise exception 'No autenticado' using errcode = '42501';
  end if;

  if not public.has_permission_secure(v_business, 'finanzas.create') then
    raise exception 'No autorizado: requiere permiso finanzas.create' using errcode = '42501';
  end if;

  for r in
    select *
    from public.recurring_transactions
    where user_id = v_business
      and is_active = true
      and next_run <= current_date
      and (end_date is null or next_run <= end_date)
    order by next_run, id
    for update skip locked
  loop
    v_guard := 0;
    while r.next_run <= current_date
      and r.is_active
      and (r.end_date is null or r.next_run <= r.end_date)
      and v_guard < 24
      and not v_limit_hit
    loop
      begin
        v_tx := public._materialize_recurring(r, false);
        if v_tx is null then
          v_skipped := v_skipped + 1;
        else
          v_created := v_created + 1;
        end if;
      exception
        when sqlstate 'P0001' then
          -- Límite del plan: paramos sin romper la sesión.
          v_limit_hit := true;
          exit;
        when others then
          v_skipped := v_skipped + 1;
          exit;
      end;

      select * into r
      from public.recurring_transactions
      where id = r.id;

      v_guard := v_guard + 1;
    end loop;
  end loop;

  return jsonb_build_object(
    'created', v_created,
    'skipped', v_skipped,
    'limit_hit', v_limit_hit
  );
end;
$$;

revoke all on function public.generate_due_recurring_transactions() from public;
grant execute on function public.generate_due_recurring_transactions() to authenticated;

-- Registra una sola ocurrencia ahora (aunque next_run sea futuro).
create or replace function public.run_recurring_now(p_id bigint)
returns bigint
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_business uuid := public.get_current_business_id();
  r public.recurring_transactions;
  v_tx bigint;
begin
  if v_business is null or auth.uid() is null then
    raise exception 'No autenticado' using errcode = '42501';
  end if;

  if not public.has_permission_secure(v_business, 'finanzas.create') then
    raise exception 'No autorizado: requiere permiso finanzas.create' using errcode = '42501';
  end if;

  select * into r
  from public.recurring_transactions
  where id = p_id and user_id = v_business
  for update;

  if not found then
    raise exception 'Plantilla no encontrada' using errcode = 'P0002';
  end if;

  if not r.is_active then
    raise exception 'Esta repetición está pausada. Actívala primero.' using errcode = 'P0001';
  end if;

  v_tx := public._materialize_recurring(r, true);
  -- null = ya existía para esa fecha, o se saltó por período cerrado.
  return v_tx;
end;
$$;

revoke all on function public.run_recurring_now(bigint) from public;
grant execute on function public.run_recurring_now(bigint) to authenticated;
