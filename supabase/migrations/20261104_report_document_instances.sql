-- E6 — Historial documental: instancias emitidas inmutables + exportaciones.
-- ID público: GESTIA-{TIPO}-{SLUG}-{AAAA}-{SEQ}
-- Un documento Emitido no se modifica (trigger); corrección = nueva versión / superseded.

create table if not exists public.report_sequences (
  user_id uuid not null default get_current_business_id() references auth.users(id),
  report_type text not null,
  year int not null,
  last_seq int not null default 0,
  primary key (user_id, report_type, year)
);

create table if not exists public.report_instances (
  id bigint generated by default as identity primary key,
  user_id uuid not null default get_current_business_id() references auth.users(id),
  public_id text not null,
  report_type text not null,
  title text not null,
  status text not null default 'draft'
    check (status in ('draft', 'issued', 'superseded', 'void')),
  version text not null default '1.0',
  replaces_id bigint references public.report_instances(id),
  period_from timestamptz,
  period_to timestamptz,
  cutoff_at timestamptz,
  timezone text,
  template_code text,
  criteria jsonb not null default '{}'::jsonb,
  filters jsonb not null default '{}'::jsonb,
  document jsonb not null,
  content_hash text not null,
  issued_at timestamptz,
  issued_by uuid references auth.users(id),
  created_by uuid references auth.users(id),
  void_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint report_instances_public_id_unique unique (public_id)
);

create index if not exists report_instances_user_created_idx
  on public.report_instances (user_id, created_at desc);
create index if not exists report_instances_user_type_idx
  on public.report_instances (user_id, report_type);

create table if not exists public.report_exports (
  id bigint generated by default as identity primary key,
  user_id uuid not null default get_current_business_id() references auth.users(id),
  instance_id bigint not null references public.report_instances(id) on delete cascade,
  format text not null check (format in ('pdf', 'docx', 'xlsx', 'json')),
  export_code text not null,
  content_hash text not null,
  generated_by uuid references auth.users(id),
  generated_at timestamptz not null default now(),
  constraint report_exports_code_unique unique (export_code)
);

create index if not exists report_exports_instance_idx
  on public.report_exports (instance_id, generated_at desc);

alter table public.report_sequences enable row level security;
alter table public.report_instances enable row level security;
alter table public.report_exports enable row level security;

