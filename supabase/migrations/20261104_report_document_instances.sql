-- Inmutabilidad: no alterar document/hash/public_id de un emitido.
create or replace function public.report_instances_prevent_issued_mutation()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if old.status = 'issued' then
    if new.document is distinct from old.document
       or new.content_hash is distinct from old.content_hash
       or new.public_id is distinct from old.public_id
       or new.report_type is distinct from old.report_type
       or new.period_from is distinct from old.period_from
       or new.period_to is distinct from old.period_to
       or new.cutoff_at is distinct from old.cutoff_at
    then
      raise exception 'report_instance_issued_immutable';
    end if;
    -- Solo se permite transición issued -> superseded|void y updated_at
    if new.status = 'issued' and (
      new.title is distinct from old.title
      or new.version is distinct from old.version
      or new.criteria is distinct from old.criteria
      or new.filters is distinct from old.filters
    ) then
      raise exception 'report_instance_issued_immutable';
    end if;
  end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists trg_report_instances_immutable on public.report_instances;
create trigger trg_report_instances_immutable
  before update on public.report_instances
  for each row execute function public.report_instances_prevent_issued_mutation();

-- Reserva atómica del número público.
create or replace function public.allocate_report_public_id(
  p_type text,
  p_slug text,
  p_year int default extract(year from now())::int
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_business uuid := get_current_business_id();
  v_seq int;
  v_slug text;
  v_type text;
begin
  if v_business is null then
    raise exception 'not_authenticated';
  end if;
  if not has_permission_secure(v_business, 'reports.export') then
    raise exception 'forbidden';
  end if;

  v_type := upper(regexp_replace(coalesce(p_type, 'REP'), '[^A-Z0-9]', '', 'g'));
  if length(v_type) < 2 then v_type := 'REP'; end if;
  v_type := left(v_type, 8);

  v_slug := upper(regexp_replace(coalesce(p_slug, 'EMP'), '[^A-Z0-9]', '', 'g'));
  if length(v_slug) < 2 then v_slug := 'EMP'; end if;
  v_slug := left(v_slug, 8);

  insert into public.report_sequences as s (user_id, report_type, year, last_seq)
  values (v_business, v_type, p_year, 1)
  on conflict (user_id, report_type, year)
  do update set last_seq = s.last_seq + 1
  returning last_seq into v_seq;

  return format('GESTIA-%s-%s-%s-%s', v_type, v_slug, p_year::text, lpad(v_seq::text, 6, '0'));
end;
$$;

revoke all on function public.allocate_report_public_id(text, text, int) from public, anon;
grant execute on function public.allocate_report_public_id(text, text, int) to authenticated;
