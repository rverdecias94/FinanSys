-- 8) Postear documento
create or replace function public.post_warehouse_document(p_doc_id bigint)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_business uuid := public.get_current_business_id();
  v_doc public.warehouse_documents%rowtype;
  v_line record;
  v_move_type text;
  v_result jsonb;
  v_results jsonb := '[]'::jsonb;
  v_unit_cost numeric;
begin
  if not public.has_permission_secure(v_business, 'warehouse.move') then
    raise exception 'No autorizado: requiere permiso warehouse.move' using errcode = '42501';
  end if;

  select * into v_doc
  from public.warehouse_documents
  where id = p_doc_id and user_id = v_business
  for update;

  if not found then
    raise exception 'Documento no encontrado' using errcode = 'P0002';
  end if;

  if v_doc.status not in ('draft', 'pending_approval') then
    raise exception 'Solo se pueden postear documentos en borrador o pendientes' using errcode = '22023';
  end if;

  if not exists (select 1 from public.warehouse_document_lines where document_id = p_doc_id) then
    raise exception 'El documento no tiene líneas' using errcode = '22023';
  end if;

  for v_line in
    select * from public.warehouse_document_lines where document_id = p_doc_id order by id
  loop
    if v_doc.doc_type in ('receipt', 'quick_in', 'return') then
      v_move_type := 'in';
      v_unit_cost := v_line.unit_cost;
    elsif v_doc.doc_type in ('issue', 'quick_out') then
      v_move_type := 'out';
      v_unit_cost := null;
    elsif v_doc.doc_type = 'adjustment' then
      -- qty siempre positiva; signo vía notes 'sign=+' / 'sign=-' o unit_cost sentinel
      -- Convención: location_to_text = 'out' para ajuste negativo; null/'in' positivo
      if coalesce(v_line.location_to_text, 'in') = 'out' then
        v_move_type := 'out';
        v_unit_cost := null;
      else
        v_move_type := 'in';
        v_unit_cost := v_line.unit_cost;
      end if;
    elsif v_doc.doc_type = 'transfer' then
      -- transferencia interna: salida + entrada (mismo qty, sin cambiar WAC en entrada)
      v_result := public.register_stock_movement(v_line.product_id, v_line.qty, 'out', null, p_doc_id);
      v_results := v_results || jsonb_build_array(v_result);
      v_result := public.register_stock_movement(v_line.product_id, v_line.qty, 'in', null, p_doc_id);
      v_results := v_results || jsonb_build_array(v_result);
      continue;
    elsif v_doc.doc_type = 'count' then
      -- count no debería postearse directo; A2 genera adjustment. Si llega, tratar como adjustment.
      if coalesce(v_line.location_to_text, 'in') = 'out' then
        v_move_type := 'out';
        v_unit_cost := null;
      else
        v_move_type := 'in';
        v_unit_cost := v_line.unit_cost;
      end if;
    else
      raise exception 'Tipo de documento no soportado: %', v_doc.doc_type using errcode = '22023';
    end if;

    v_result := public.register_stock_movement(
      v_line.product_id, v_line.qty, v_move_type, v_unit_cost, p_doc_id
    );
    v_results := v_results || jsonb_build_array(v_result);
  end loop;

  update public.warehouse_documents
    set status = 'posted',
        posted_at = now(),
        updated_at = now(),
        approved_by = coalesce(approved_by, auth.uid())
  where id = p_doc_id;

  return jsonb_build_object(
    'document_id', p_doc_id,
    'doc_number', v_doc.doc_number,
    'status', 'posted',
    'movements', v_results
  );
end;
$$;

revoke all on function public.post_warehouse_document(bigint) from public;
grant execute on function public.post_warehouse_document(bigint) to authenticated;

-- 9) Movimiento rápido (doc auto + post)
create or replace function public.create_and_post_quick_movement(
  p_product_id bigint,
  p_qty numeric,
  p_type text,
  p_unit_cost numeric default null,
  p_notes text default null
)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_business uuid := public.get_current_business_id();
  v_doc_id bigint;
  v_doc_type text;
  v_prefix text;
  v_number text;
  v_posted jsonb;
begin
  if p_type not in ('in','out') then
    raise exception 'Tipo de movimiento invalido: %', p_type using errcode = '22023';
  end if;
  if not public.has_permission_secure(v_business, 'warehouse.move') then
    raise exception 'No autorizado: requiere permiso warehouse.move' using errcode = '42501';
  end if;

  v_doc_type := case when p_type = 'in' then 'quick_in' else 'quick_out' end;
  v_prefix := case when p_type = 'in' then 'QIN' else 'QOUT' end;
  v_number := public.next_warehouse_doc_number(v_prefix);

  insert into public.warehouse_documents (
    user_id, doc_type, doc_number, status, notes, created_by
  ) values (
    v_business, v_doc_type, v_number, 'draft', p_notes, auth.uid()
  ) returning id into v_doc_id;

  insert into public.warehouse_document_lines (document_id, product_id, qty, unit_cost)
  values (v_doc_id, p_product_id, p_qty, case when p_type = 'in' then p_unit_cost else null end);

  v_posted := public.post_warehouse_document(v_doc_id);

  return v_posted || jsonb_build_object(
    'product_id', p_product_id,
    'qty', p_qty,
    'type', p_type,
    'name', (select name from public.products where id = p_product_id and user_id = v_business),
    'new_stock', (select stock from public.products where id = p_product_id and user_id = v_business),
    'unit_cost', case
      when p_type = 'in' then p_unit_cost
      else (select avg_cost from public.products where id = p_product_id and user_id = v_business)
    end,
    'doc_number', v_number
  );
end;
$$;

revoke all on function public.create_and_post_quick_movement(bigint, numeric, text, numeric, text) from public;
grant execute on function public.create_and_post_quick_movement(bigint, numeric, text, numeric, text) to authenticated;

-- 10) Reverso de documento postado
create or replace function public.reverse_warehouse_document(p_doc_id bigint, p_notes text default null)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_business uuid := public.get_current_business_id();
  v_doc public.warehouse_documents%rowtype;
  v_rev_id bigint;
  v_number text;
  v_line record;
  v_posted jsonb;
begin
  if not public.has_permission_secure(v_business, 'warehouse.move') then
    raise exception 'No autorizado: requiere permiso warehouse.move' using errcode = '42501';
  end if;

  select * into v_doc
  from public.warehouse_documents
  where id = p_doc_id and user_id = v_business
  for update;

  if not found then
    raise exception 'Documento no encontrado' using errcode = 'P0002';
  end if;
  if v_doc.status <> 'posted' then
    raise exception 'Solo se pueden revertir documentos postados' using errcode = '22023';
  end if;

  v_number := public.next_warehouse_doc_number('REV');

  insert into public.warehouse_documents (
    user_id, doc_type, doc_number, status, notes, source_ref, reversed_of, created_by
  ) values (
    v_business, v_doc.doc_type, v_number, 'draft',
    coalesce(p_notes, 'Reverso de ' || v_doc.doc_number),
    v_doc.doc_number, p_doc_id, auth.uid()
  ) returning id into v_rev_id;

  for v_line in
    select * from public.warehouse_document_lines where document_id = p_doc_id order by id
  loop
    insert into public.warehouse_document_lines (
      document_id, product_id, qty, unit_cost, lot_text, serial_text,
      location_text, location_to_text, notes
    ) values (
      v_rev_id, v_line.product_id, v_line.qty, v_line.unit_cost, v_line.lot_text, v_line.serial_text,
      v_line.location_text,
      -- invertir sentido de ajuste
      case
        when v_doc.doc_type in ('adjustment','count') then
          case when coalesce(v_line.location_to_text, 'in') = 'out' then 'in' else 'out' end
        when v_doc.doc_type in ('receipt','quick_in','return') then 'out'
        when v_doc.doc_type in ('issue','quick_out') then 'in'
        when v_doc.doc_type = 'transfer' then v_line.location_to_text
        else coalesce(v_line.location_to_text, 'out')
      end,
      'reverso'
    );
  end loop;

  -- Para reverso de quick_in/receipt → necesitamos doc_type que genere outs.
  -- Reescribimos temporalmente el tipo del reverso para post_warehouse_document.
  if v_doc.doc_type in ('receipt','quick_in','return') then
    update public.warehouse_documents set doc_type = 'quick_out' where id = v_rev_id;
  elsif v_doc.doc_type in ('issue','quick_out') then
    update public.warehouse_documents set doc_type = 'quick_in' where id = v_rev_id;
  elsif v_doc.doc_type = 'transfer' then
    -- transfer ya hace out+in; re-postear transfer restaura ubicaciones lógicas
    null;
  else
    update public.warehouse_documents set doc_type = 'adjustment' where id = v_rev_id;
  end if;

  v_posted := public.post_warehouse_document(v_rev_id);

  update public.warehouse_documents
    set status = 'reversed', updated_at = now()
  where id = p_doc_id;

  return jsonb_build_object(
    'original_id', p_doc_id,
    'reversal_id', v_rev_id,
    'reversal_number', v_number,
    'result', v_posted
  );
end;
$$;

revoke all on function public.reverse_warehouse_document(bigint, text) from public;
grant execute on function public.reverse_warehouse_document(bigint, text) to authenticated;

-- 11) Seed motivos globales por negocio (al primer uso vía función helper)
create or replace function public.ensure_warehouse_reason_codes()
returns void
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_business uuid := public.get_current_business_id();
begin
  if v_business is null then return; end if;
