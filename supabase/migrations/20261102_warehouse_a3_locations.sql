-- Backfill: crear almacén default para negocios con productos
insert into public.warehouses (user_id, name, is_default, is_active)
select distinct p.user_id, 'Principal', true, true
from public.products p
where not exists (
  select 1 from public.warehouses w where w.user_id = p.user_id and w.is_default
)
on conflict do nothing;
