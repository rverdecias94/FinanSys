-- Asegurar almacén default por negocio
create or replace function public.ensure_default_warehouse()
returns bigint
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_business uuid := public.get_current_business_id();
  v_id bigint;
begin
  if v_business is null then
    raise exception 'Negocio no resuelto' using errcode = '42501';
  end if;

  select id into v_id from public.warehouses
  where user_id = v_business and is_default = true
  limit 1;

  if v_id is null then
    insert into public.warehouses (user_id, name, is_default, is_active)
    values (v_business, 'Principal', true, true)
    returning id into v_id;
  end if;
  return v_id;
end;
$$;

revoke all on function public.ensure_default_warehouse() from public;
grant execute on function public.ensure_default_warehouse() to authenticated;

-- Ajustar saldo por ubicación (interno)
create or replace function public.apply_stock_balance_delta(
  p_product_id bigint,
  p_warehouse_id bigint,
  p_location_id bigint,
  p_delta numeric
)
returns void
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_business uuid := public.get_current_business_id();
  v_qty numeric;
begin
  if p_warehouse_id is null then
    return;
  end if;

  select qty into v_qty
  from public.stock_balances
  where user_id = v_business
    and product_id = p_product_id
    and warehouse_id = p_warehouse_id
    and coalesce(location_id, -1) = coalesce(p_location_id, -1)
  for update;

  if not found then
    if p_delta < 0 then
      raise exception 'Stock insuficiente en la ubicación' using errcode = '23514';
    end if;
    insert into public.stock_balances (user_id, product_id, warehouse_id, location_id, qty)
    values (v_business, p_product_id, p_warehouse_id, p_location_id, p_delta);
    return;
  end if;

  if v_qty + p_delta < 0 then
    raise exception 'Stock insuficiente en la ubicación' using errcode = '23514';
  end if;

  update public.stock_balances
    set qty = qty + p_delta, updated_at = now()
  where user_id = v_business
    and product_id = p_product_id
    and warehouse_id = p_warehouse_id
    and coalesce(location_id, -1) = coalesce(p_location_id, -1);
end;
$$;

revoke all on function public.apply_stock_balance_delta(bigint, bigint, bigint, numeric) from public;
