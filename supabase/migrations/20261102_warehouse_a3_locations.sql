-- A3 — Estructura física ligera: warehouses + locations + stock_balances
-- ----------------------------------------------------------------------------

create table if not exists public.warehouses (
  id bigint generated by default as identity primary key,
  user_id uuid not null default public.get_current_business_id() references auth.users(id),
  name text not null,
  is_default boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (user_id, name)
);

create unique index if not exists idx_warehouses_one_default
  on public.warehouses (user_id) where is_default = true;

create table if not exists public.warehouse_locations (
  id bigint generated by default as identity primary key,
  warehouse_id bigint not null references public.warehouses(id) on delete cascade,
  user_id uuid not null default public.get_current_business_id() references auth.users(id),
  code text not null,
  name text,
  zone_text text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (warehouse_id, code)
);

create table if not exists public.stock_balances (
  id bigint generated by default as identity primary key,
  user_id uuid not null default public.get_current_business_id() references auth.users(id),
  product_id bigint not null references public.products(id) on delete cascade,
  warehouse_id bigint not null references public.warehouses(id),
  location_id bigint references public.warehouse_locations(id) on delete restrict,
  qty numeric not null default 0 check (qty >= 0),
  updated_at timestamptz not null default now()
);

-- location_id nullable: UNIQUE estándar no cubre varios NULL; usamos coalesce.
create unique index if not exists idx_stock_balances_dims
  on public.stock_balances (user_id, product_id, warehouse_id, (coalesce(location_id, -1)));

create index if not exists idx_stock_balances_product
  on public.stock_balances (user_id, product_id);

alter table public.warehouses enable row level security;
alter table public.warehouse_locations enable row level security;
alter table public.stock_balances enable row level security;

