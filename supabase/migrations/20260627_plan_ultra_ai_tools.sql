-- 2) Uso mensual de IA -------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ai_usage (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  period_start date NOT NULL,
  doc_pages_used integer NOT NULL DEFAULT 0 CHECK (doc_pages_used >= 0),
  calc_queries_used integer NOT NULL DEFAULT 0 CHECK (calc_queries_used >= 0),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (business_id, period_start)
);

CREATE INDEX IF NOT EXISTS idx_ai_usage_business_period
  ON public.ai_usage (business_id, period_start DESC);

ALTER TABLE public.ai_usage ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS ai_usage_select ON public.ai_usage;
CREATE POLICY ai_usage_select ON public.ai_usage
FOR SELECT TO authenticated
USING (
  auth.uid() = business_id
  OR public.is_member_of_team(business_id)
  OR public.is_system_admin()
);

GRANT SELECT ON public.ai_usage TO authenticated;

-- 3) Helpers de plan de pago ------------------------------------------------
CREATE OR REPLACE FUNCTION public.is_paid_plan_id(p_plan text)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
SET search_path = public, pg_temp
AS $$
  SELECT p_plan IN ('premium', 'ultra');
$$;

CREATE OR REPLACE FUNCTION public.plan_price_for_cycle(p_plan_id text, p_cycle text)
RETURNS numeric
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
SET row_security = off
AS $$
  SELECT COALESCE(
    (SELECT (pricing ->> p_cycle)::numeric FROM public.plans WHERE id = p_plan_id),
    0
  );
$$;

-- Compat: premium_price_for_cycle sigue leyendo premium
CREATE OR REPLACE FUNCTION public.premium_price_for_cycle(p_cycle text)
RETURNS numeric
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
SET row_security = off
AS $$
  SELECT public.plan_price_for_cycle('premium', p_cycle);
$$;

-- is_premium: Ultra también cuenta (equipo / RLS)
CREATE OR REPLACE FUNCTION public.is_premium(check_user_id uuid)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  sub record;
BEGIN
  SELECT * INTO sub FROM public.subscriptions WHERE user_id = check_user_id;
  IF sub.user_id IS NULL THEN
    RETURN FALSE;
  END IF;

  IF public.is_paid_plan_id(sub.plan_id) AND sub.status = 'active' THEN
    RETURN TRUE;
  END IF;

  IF sub.status = 'trial' AND sub.trial_end_at IS NOT NULL AND sub.trial_end_at > NOW() THEN
    RETURN TRUE;
  END IF;

  RETURN FALSE;
END;
$$;

-- 4) Estado efectivo / plan id (premium|ultra con gracia) --------------------
CREATE OR REPLACE FUNCTION public.get_effective_plan_state(target_business_id uuid)
RETURNS json
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
SET row_security = off
AS $$
DECLARE
  sub record;
  v_lead_days integer;
  v_grace_days integer;
  v_state text;
  v_grace_until timestamptz;
  v_days_until_due integer;
  v_now timestamptz := now();
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'No autenticado' USING ERRCODE = 'P0001';
  END IF;
  IF NOT (auth.uid() = target_business_id OR public.is_member_of_team(target_business_id) OR public.is_system_admin()) THEN
    RAISE EXCEPTION 'No autorizado' USING ERRCODE = 'P0001';
  END IF;

  SELECT bc.reminder_lead_days, bc.grace_days INTO v_lead_days, v_grace_days
  FROM public.billing_config bc WHERE bc.id = 1;
  v_lead_days := COALESCE(v_lead_days, 7);
  v_grace_days := COALESCE(v_grace_days, 3);

  SELECT * INTO sub FROM public.subscriptions WHERE user_id = target_business_id LIMIT 1;

  IF EXISTS (
    SELECT 1 FROM public.account_status acc
    WHERE acc.user_id = target_business_id AND acc.status IN ('suspended','deleted')
  ) THEN
    RETURN json_build_object(
      'plan_id', COALESCE(sub.plan_id, 'free'), 'status', COALESCE(sub.status, 'active'),
      'payment_state', 'blocked', 'current_period_end', sub.current_period_end,
      'grace_until', NULL, 'days_until_due', NULL,
      'billing_cycle', COALESCE(sub.billing_cycle, 'monthly'),
      'lead_days', v_lead_days, 'grace_days', v_grace_days
    );
  END IF;

  IF sub.user_id IS NULL OR NOT public.is_paid_plan_id(sub.plan_id) THEN
    RETURN json_build_object(
      'plan_id', COALESCE(sub.plan_id, 'free'), 'status', COALESCE(sub.status, 'active'),
      'payment_state', 'free', 'current_period_end', sub.current_period_end,
      'grace_until', NULL, 'days_until_due', NULL,
      'billing_cycle', COALESCE(sub.billing_cycle, 'monthly'),
      'lead_days', v_lead_days, 'grace_days', v_grace_days
    );
  END IF;

  IF sub.current_period_end IS NULL THEN
    v_state := 'ok'; v_grace_until := NULL; v_days_until_due := NULL;
  ELSE
    v_grace_until := sub.current_period_end + make_interval(days => v_grace_days);
    v_days_until_due := CEIL(EXTRACT(EPOCH FROM (sub.current_period_end - v_now)) / 86400.0)::integer;
    IF v_now <= sub.current_period_end - make_interval(days => v_lead_days) THEN v_state := 'ok';
    ELSIF v_now <= sub.current_period_end THEN v_state := 'due_soon';
    ELSIF v_now <= v_grace_until THEN v_state := 'grace';
    ELSE v_state := 'blocked';
    END IF;
  END IF;

  IF sub.status = 'suspended' THEN v_state := 'blocked'; END IF;

  RETURN json_build_object(
    'plan_id', sub.plan_id,
    'status', sub.status,
    'payment_state', v_state,
    'current_period_end', sub.current_period_end,
    'grace_until', v_grace_until,
    'days_until_due', v_days_until_due,
    'billing_cycle', COALESCE(sub.billing_cycle, 'monthly'),
    'lead_days', v_lead_days,
    'grace_days', v_grace_days
  );
END;
$$;

GRANT EXECUTE ON FUNCTION public.get_effective_plan_state(uuid) TO authenticated;
REVOKE EXECUTE ON FUNCTION public.get_effective_plan_state(uuid) FROM anon, public;

CREATE OR REPLACE FUNCTION public.get_effective_plan_id(target_user uuid)
RETURNS text
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
SET row_security = off
AS $$
DECLARE
  v_plan text;
  v_status text;
  v_end timestamptz;
  v_grace integer;
BEGIN
  SELECT plan_id, status, current_period_end INTO v_plan, v_status, v_end
  FROM public.subscriptions WHERE user_id = target_user LIMIT 1;

  IF v_plan IS NULL THEN
    RETURN 'free';
  END IF;

  IF public.is_paid_plan_id(v_plan) THEN
    IF v_status = 'suspended' THEN
      RETURN 'free';
    END IF;
    IF v_end IS NOT NULL THEN
      SELECT grace_days INTO v_grace FROM public.billing_config WHERE id = 1;
      v_grace := COALESCE(v_grace, 3);
      IF now() > v_end + make_interval(days => v_grace) THEN
        RETURN 'free';
      END IF;
    END IF;
    RETURN v_plan;
  END IF;

  RETURN v_plan;
END;
$$;

REVOKE ALL ON FUNCTION public.get_effective_plan_id(uuid) FROM public, anon, authenticated;

-- 5) Solicitar Premium u Ultra -----------------------------------------------
CREATE OR REPLACE FUNCTION public.request_plan_change(
  target_plan_id text,
  requested_months integer DEFAULT 1,
  contact_phone text DEFAULT NULL,
  payment_method text DEFAULT NULL,
  payment_reference text DEFAULT NULL,
  user_notes text DEFAULT NULL,
  billing_cycle text DEFAULT NULL
)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
SET row_security = off
AS $$
DECLARE
  v_business_id uuid;
  current_plan text;
  request_id uuid;
  current_email text;
  v_cycle text;
  v_months integer;
  v_amount numeric;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'No autenticado' USING ERRCODE = 'P0001';
  END IF;

  v_business_id := public.get_current_business_id();
  IF v_business_id IS NULL OR v_business_id <> auth.uid() THEN
    RAISE EXCEPTION 'Solo el propietario puede solicitar cambios de plan' USING ERRCODE = 'P0001';
  END IF;

  IF target_plan_id IS NULL OR NOT public.is_paid_plan_id(target_plan_id) THEN
    RAISE EXCEPTION 'Solo se permiten solicitudes manuales para Premium u Ultra' USING ERRCODE = 'P0001';
  END IF;

  v_cycle := NULLIF(trim(billing_cycle), '');
  IF v_cycle IS NOT NULL AND v_cycle NOT IN ('monthly','quarterly','semiannual','annual') THEN
    RAISE EXCEPTION 'Ciclo de facturación inválido' USING ERRCODE = 'P0001';
  END IF;
  IF v_cycle IS NULL THEN
    IF requested_months IS NULL OR requested_months < 1 THEN requested_months := 1; END IF;
    v_cycle := CASE requested_months
      WHEN 12 THEN 'annual'
      WHEN 6 THEN 'semiannual'
      WHEN 3 THEN 'quarterly'
      WHEN 1 THEN 'monthly'
      ELSE 'monthly'
    END;
  END IF;
  v_months := public.billing_cycle_months(v_cycle);
  v_amount := public.plan_price_for_cycle(target_plan_id, v_cycle);

  SELECT COALESCE(s.plan_id, 'free') INTO current_plan
  FROM public.subscriptions s
  WHERE s.user_id = v_business_id
  LIMIT 1;
  current_plan := COALESCE(current_plan, 'free');

  IF current_plan = target_plan_id THEN
    RAISE EXCEPTION 'El negocio ya tiene ese plan activo' USING ERRCODE = 'P0001';
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.plan_change_requests pcr
    WHERE pcr.business_id = v_business_id AND pcr.status = 'pending'
  ) THEN
    RAISE EXCEPTION 'Ya existe una solicitud pendiente para este negocio' USING ERRCODE = 'P0001';
  END IF;

  current_email := public.get_current_user_email();

  INSERT INTO public.plan_change_requests (
    business_id, requested_by, requested_plan_id, current_plan_id,
    requested_months, billing_cycle, requested_amount,
    contact_phone, contact_email, payment_method, payment_reference, user_notes
  )
  VALUES (
    v_business_id, auth.uid(), target_plan_id, current_plan,
    v_months, v_cycle, v_amount,
    NULLIF(trim(contact_phone), ''), NULLIF(current_email, ''),
    NULLIF(trim(payment_method), ''), NULLIF(trim(payment_reference), ''), NULLIF(trim(user_notes), '')
  )
  RETURNING id INTO request_id;

  INSERT INTO public.audit_logs (business_id, actor_id, user_id, user_email, action, resource, details, area)
  VALUES (
    v_business_id, auth.uid(), auth.uid(), current_email, 'Solicitar Plan',
    CASE WHEN target_plan_id = 'ultra' THEN 'Plan Ultra' ELSE 'Plan Premium' END,
    jsonb_build_object(
      'request_id', request_id, 'current_plan', current_plan, 'requested_plan', target_plan_id,
      'billing_cycle', v_cycle, 'requested_months', v_months, 'requested_amount', v_amount
    ),
    'Planes'
  );

  RETURN json_build_object(
    'request_id', request_id, 'status', 'pending',
    'billing_cycle', v_cycle, 'amount', v_amount, 'plan_id', target_plan_id
  );
END;
$$;

GRANT EXECUTE ON FUNCTION public.request_plan_change(text, integer, text, text, text, text, text) TO authenticated;
REVOKE EXECUTE ON FUNCTION public.request_plan_change(text, integer, text, text, text, text, text) FROM anon, public;

-- 6) Aprobar solicitud (pago según plan) -------------------------------------
CREATE OR REPLACE FUNCTION public.approve_plan_change_request(
  request_id uuid,
  approved_months integer DEFAULT NULL,
  admin_notes text DEFAULT NULL,
  billing_cycle text DEFAULT NULL
)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
SET row_security = off
AS $$
DECLARE
  req record;
  months integer;
  v_cycle text;
  v_amount numeric;
  v_payment_id bigint;
  period_start timestamptz;
  period_end timestamptz;
  admin_email text;
  v_admin_notes text;
BEGIN
  IF NOT public.is_system_admin() THEN
    RAISE EXCEPTION 'Solo un administrador del sistema puede aprobar solicitudes' USING ERRCODE = 'P0001';
  END IF;

  SELECT * INTO req FROM public.plan_change_requests WHERE id = request_id FOR UPDATE;
  IF req.id IS NULL THEN RAISE EXCEPTION 'Solicitud no encontrada' USING ERRCODE = 'P0001'; END IF;
  IF req.status <> 'pending' THEN RAISE EXCEPTION 'La solicitud ya fue procesada' USING ERRCODE = 'P0001'; END IF;

  v_cycle := NULLIF(trim(billing_cycle), '');
  IF v_cycle IS NULL THEN v_cycle := req.billing_cycle; END IF;
  IF v_cycle IS NOT NULL AND v_cycle NOT IN ('monthly','quarterly','semiannual','annual') THEN
    RAISE EXCEPTION 'Ciclo de facturación inválido' USING ERRCODE = 'P0001';
  END IF;

  IF v_cycle IS NOT NULL THEN
    months := public.billing_cycle_months(v_cycle);
  ELSE
    months := COALESCE(approved_months, req.requested_months, 1);
    IF months < 1 THEN months := 1; END IF;
    v_cycle := CASE months
      WHEN 12 THEN 'annual'
      WHEN 6 THEN 'semiannual'
      WHEN 3 THEN 'quarterly'
      WHEN 1 THEN 'monthly'
      ELSE 'monthly'
    END;
  END IF;

  v_admin_notes := NULLIF(trim(admin_notes), '');
  period_start := now();
  period_end := period_start + make_interval(months => months);
  admin_email := public.get_current_user_email();

  INSERT INTO public.subscriptions (
    user_id, plan_id, status, billing_cycle, current_period_start, current_period_end,
    source, approved_by, approved_at, admin_notes, created_at, updated_at
  )
  VALUES (
    req.business_id, req.requested_plan_id, 'active', v_cycle, period_start, period_end,
    'manual', auth.uid(), now(), v_admin_notes, now(), now()
  )
  ON CONFLICT (user_id) DO UPDATE
  SET plan_id = excluded.plan_id, status = excluded.status, billing_cycle = excluded.billing_cycle,
      current_period_start = excluded.current_period_start, current_period_end = excluded.current_period_end,
      source = excluded.source, approved_by = excluded.approved_by, approved_at = excluded.approved_at,
      admin_notes = excluded.admin_notes, trial_start_at = NULL, trial_end_at = NULL,
      cancelled_by = NULL, cancelled_at = NULL, updated_at = now();

  UPDATE public.plan_change_requests
  SET status = 'approved', reviewed_by = auth.uid(), reviewed_at = now(), admin_notes = v_admin_notes, updated_at = now()
  WHERE id = req.id;

  IF public.is_paid_plan_id(req.requested_plan_id) THEN
    v_amount := COALESCE(req.requested_amount, public.plan_price_for_cycle(req.requested_plan_id, v_cycle));
    INSERT INTO public.payments (
      business_id, amount, currency_code, billing_cycle, period_start, period_end,
      paid_at, method, reference, status, request_id, recorded_by, notes
    )
    VALUES (
      req.business_id, COALESCE(v_amount, 0), 'USD', v_cycle, period_start, period_end,
      now(), req.payment_method, req.payment_reference, 'paid', req.id, auth.uid(), v_admin_notes
    )
    RETURNING id INTO v_payment_id;
  END IF;

  INSERT INTO public.audit_logs (business_id, actor_id, user_id, user_email, action, resource, details, area)
  VALUES (
    req.business_id, auth.uid(), auth.uid(), admin_email, 'Aprobar Plan',
    CASE WHEN req.requested_plan_id = 'ultra' THEN 'Plan Ultra' ELSE 'Plan Premium' END,
    jsonb_build_object(
      'request_id', req.id, 'approved_plan', req.requested_plan_id, 'approved_months', months,
      'billing_cycle', v_cycle, 'period_end', period_end, 'payment_id', v_payment_id
    ),
    'Planes'
  );

  RETURN json_build_object(
    'request_id', req.id, 'business_id', req.business_id, 'plan_id', req.requested_plan_id,
    'status', 'approved', 'current_period_end', period_end, 'billing_cycle', v_cycle,
    'payment_id', v_payment_id
  );
END;
$$;

GRANT EXECUTE ON FUNCTION public.approve_plan_change_request(uuid, integer, text, text) TO authenticated;
REVOKE EXECUTE ON FUNCTION public.approve_plan_change_request(uuid, integer, text, text) FROM anon, public;

-- 7) Admin set plan (free|premium|ultra) -------------------------------------
CREATE OR REPLACE FUNCTION public.admin_set_business_plan(
  target_business_id uuid,
  target_plan_id text,
  months integer DEFAULT NULL,
  admin_notes text DEFAULT NULL,
  billing_cycle text DEFAULT NULL
)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
SET row_security = off
AS $$
DECLARE
  m integer;
  v_cycle text;
  v_amount numeric;
  v_payment_id bigint;
  period_start timestamptz;
  period_end timestamptz;
  admin_email text;
  v_admin_notes text;
BEGIN
  IF NOT public.is_system_admin() THEN
    RAISE EXCEPTION 'Solo un administrador del sistema puede cambiar planes' USING ERRCODE = 'P0001';
  END IF;
  IF target_business_id IS NULL THEN
    RAISE EXCEPTION 'business_id requerido' USING ERRCODE = 'P0001';
  END IF;
  IF target_plan_id IS NULL OR target_plan_id NOT IN ('free', 'premium', 'ultra') THEN
    RAISE EXCEPTION 'plan_id inválido' USING ERRCODE = 'P0001';
  END IF;

  v_admin_notes := NULLIF(trim(admin_notes), '');
  admin_email := public.get_current_user_email();

  v_cycle := NULLIF(trim(billing_cycle), '');
  IF v_cycle IS NOT NULL AND v_cycle NOT IN ('monthly','quarterly','semiannual','annual') THEN
    RAISE EXCEPTION 'Ciclo de facturación inválido' USING ERRCODE = 'P0001';
  END IF;

  IF public.is_paid_plan_id(target_plan_id) THEN
    IF v_cycle IS NOT NULL THEN
      m := public.billing_cycle_months(v_cycle);
    ELSE
      m := COALESCE(months, 1);
      IF m < 1 THEN m := 1; END IF;
      v_cycle := CASE m
        WHEN 12 THEN 'annual'
        WHEN 6 THEN 'semiannual'
        WHEN 3 THEN 'quarterly'
        WHEN 1 THEN 'monthly'
        ELSE 'monthly'
      END;
    END IF;

    period_start := now();
    period_end := period_start + make_interval(months => m);

    INSERT INTO public.subscriptions (
      user_id, plan_id, status, billing_cycle, current_period_start, current_period_end,
      source, approved_by, approved_at, admin_notes, created_at, updated_at
    )
    VALUES (
      target_business_id, target_plan_id, 'active', v_cycle, period_start, period_end,
      'admin', auth.uid(), now(), v_admin_notes, now(), now()
    )
    ON CONFLICT (user_id) DO UPDATE
    SET plan_id = excluded.plan_id,
        status = excluded.status,
        billing_cycle = excluded.billing_cycle,
        current_period_start = excluded.current_period_start,
        current_period_end = excluded.current_period_end,
        source = excluded.source,
        approved_by = excluded.approved_by,
        approved_at = excluded.approved_at,
        admin_notes = excluded.admin_notes,
        trial_start_at = NULL,
        trial_end_at = NULL,
        cancelled_by = NULL,
        cancelled_at = NULL,
        updated_at = now();

    v_amount := public.plan_price_for_cycle(target_plan_id, v_cycle);
    INSERT INTO public.payments (
      business_id, amount, currency_code, billing_cycle, period_start, period_end,
      paid_at, method, reference, status, recorded_by, notes
    )
    VALUES (
      target_business_id, COALESCE(v_amount, 0), 'USD', v_cycle, period_start, period_end,
      now(), 'admin', NULL, 'paid', auth.uid(), v_admin_notes
    )
    RETURNING id INTO v_payment_id;
  ELSE
    INSERT INTO public.subscriptions (
      user_id, plan_id, status, current_period_start, current_period_end,
      source, cancelled_by, cancelled_at, admin_notes, created_at, updated_at
    )
    VALUES (
      target_business_id, 'free', 'cancelled', now(), NULL,
      'admin', auth.uid(), now(), v_admin_notes, now(), now()
    )
    ON CONFLICT (user_id) DO UPDATE
    SET plan_id = 'free',
        status = 'cancelled',
        current_period_end = NULL,
        source = 'admin',
        cancelled_by = auth.uid(),
        cancelled_at = now(),
        admin_notes = v_admin_notes,
        updated_at = now();
  END IF;

  INSERT INTO public.audit_logs (business_id, actor_id, user_id, user_email, action, resource, details, area)
  VALUES (
    target_business_id, auth.uid(), auth.uid(), admin_email, 'Ajuste Plan',
    CASE WHEN target_plan_id = 'ultra' THEN 'Plan Ultra'
         WHEN target_plan_id = 'premium' THEN 'Plan Premium'
         ELSE 'Plan Gratuito' END,
    jsonb_build_object(
      'target_plan', target_plan_id, 'months', m, 'billing_cycle', v_cycle, 'payment_id', v_payment_id
    ),
    'Planes'
  );

  RETURN json_build_object(
    'business_id', target_business_id,
    'plan_id', target_plan_id,
    'billing_cycle', v_cycle,
    'current_period_end', period_end,
    'payment_id', v_payment_id
  );
END;
$$;

