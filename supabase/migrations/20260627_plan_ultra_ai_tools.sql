REVOKE EXECUTE ON FUNCTION public.admin_set_business_plan(uuid, text, integer, text, text) FROM anon, public;

-- 8) Cupos IA ----------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.get_ai_usage(p_business_id uuid DEFAULT NULL)
RETURNS json
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
SET row_security = off
AS $$
DECLARE
  v_business uuid;
  v_period date;
  v_row public.ai_usage%ROWTYPE;
  v_plan text;
  v_doc_limit integer;
  v_calc_limit integer;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'No autenticado' USING ERRCODE = 'P0001';
  END IF;

  v_business := COALESCE(p_business_id, public.get_current_business_id());
  IF v_business IS NULL THEN
    RAISE EXCEPTION 'Negocio no resuelto' USING ERRCODE = 'P0001';
  END IF;
  IF NOT (auth.uid() = v_business OR public.is_member_of_team(v_business) OR public.is_system_admin()) THEN
    RAISE EXCEPTION 'No autorizado' USING ERRCODE = 'P0001';
  END IF;

  v_period := date_trunc('month', now())::date;
  v_plan := public.get_effective_plan_id(v_business);

  SELECT COALESCE((limits ->> 'ai_doc_pages')::integer, 0),
         COALESCE((limits ->> 'ai_calc_queries')::integer, 0)
  INTO v_doc_limit, v_calc_limit
  FROM public.plans WHERE id = v_plan;

  IF v_doc_limit IS NULL OR v_doc_limit < 0 THEN v_doc_limit := 0; END IF;
  IF v_calc_limit IS NULL OR v_calc_limit < 0 THEN v_calc_limit := 0; END IF;

  SELECT * INTO v_row FROM public.ai_usage
  WHERE business_id = v_business AND period_start = v_period;

  RETURN json_build_object(
    'business_id', v_business,
    'period_start', v_period,
    'plan_id', v_plan,
    'doc_pages_used', COALESCE(v_row.doc_pages_used, 0),
    'calc_queries_used', COALESCE(v_row.calc_queries_used, 0),
    'doc_pages_limit', v_doc_limit,
    'calc_queries_limit', v_calc_limit,
    'ai_tools', COALESCE((SELECT (features ->> 'ai_tools')::boolean FROM public.plans WHERE id = v_plan), false)
  );
END;
$$;

GRANT EXECUTE ON FUNCTION public.get_ai_usage(uuid) TO authenticated;
REVOKE EXECUTE ON FUNCTION public.get_ai_usage(uuid) FROM anon, public;

CREATE OR REPLACE FUNCTION public.consume_ai_quota(
  p_kind text,
  p_units integer DEFAULT 1,
  p_business_id uuid DEFAULT NULL
)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
SET row_security = off
AS $$
DECLARE
  v_business uuid;
  v_period date;
  v_plan text;
  v_limit integer;
  v_used integer;
  v_new integer;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'No autenticado' USING ERRCODE = 'P0001';
  END IF;

  IF p_kind IS NULL OR p_kind NOT IN ('doc_pages', 'calc_queries') THEN
    RAISE EXCEPTION 'Tipo de cupo inválido' USING ERRCODE = 'P0001';
  END IF;
  IF p_units IS NULL OR p_units < 1 THEN
    RAISE EXCEPTION 'Unidades inválidas' USING ERRCODE = 'P0001';
  END IF;

  v_business := COALESCE(p_business_id, public.get_current_business_id());
  IF v_business IS NULL THEN
    RAISE EXCEPTION 'Negocio no resuelto' USING ERRCODE = 'P0001';
  END IF;
  IF NOT (auth.uid() = v_business OR public.is_member_of_team(v_business)) THEN
    RAISE EXCEPTION 'No autorizado' USING ERRCODE = 'P0001';
  END IF;

  v_plan := public.get_effective_plan_id(v_business);
  IF v_plan IS DISTINCT FROM 'ultra' THEN
    RAISE EXCEPTION 'Las herramientas de IA requieren el plan Ultra' USING ERRCODE = 'P0001';
  END IF;

  v_period := date_trunc('month', now())::date;

  IF p_kind = 'doc_pages' THEN
    SELECT COALESCE((limits ->> 'ai_doc_pages')::integer, 0) INTO v_limit FROM public.plans WHERE id = 'ultra';
  ELSE
    SELECT COALESCE((limits ->> 'ai_calc_queries')::integer, 0) INTO v_limit FROM public.plans WHERE id = 'ultra';
  END IF;

  INSERT INTO public.ai_usage (business_id, period_start, doc_pages_used, calc_queries_used, updated_at)
  VALUES (v_business, v_period, 0, 0, now())
  ON CONFLICT (business_id, period_start) DO NOTHING;

  -- Bloqueo de fila para consumo atómico
  IF p_kind = 'doc_pages' THEN
    SELECT doc_pages_used INTO v_used FROM public.ai_usage
    WHERE business_id = v_business AND period_start = v_period FOR UPDATE;
    IF v_used + p_units > v_limit THEN
      RAISE EXCEPTION 'Cupo mensual de páginas agotado (% / %)', v_used, v_limit USING ERRCODE = 'P0001';
    END IF;
    UPDATE public.ai_usage
    SET doc_pages_used = doc_pages_used + p_units, updated_at = now()
    WHERE business_id = v_business AND period_start = v_period
    RETURNING doc_pages_used INTO v_new;
  ELSE
    SELECT calc_queries_used INTO v_used FROM public.ai_usage
    WHERE business_id = v_business AND period_start = v_period FOR UPDATE;
    IF v_used + p_units > v_limit THEN
      RAISE EXCEPTION 'Cupo mensual de consultas agotado (% / %)', v_used, v_limit USING ERRCODE = 'P0001';
    END IF;
    UPDATE public.ai_usage
    SET calc_queries_used = calc_queries_used + p_units, updated_at = now()
    WHERE business_id = v_business AND period_start = v_period
    RETURNING calc_queries_used INTO v_new;
  END IF;

  RETURN json_build_object(
    'kind', p_kind,
    'units', p_units,
    'used', v_new,
    'limit', v_limit,
    'period_start', v_period
  );
END;
$$;

GRANT EXECUTE ON FUNCTION public.consume_ai_quota(text, integer, uuid) TO authenticated;
REVOKE EXECUTE ON FUNCTION public.consume_ai_quota(text, integer, uuid) FROM anon, public;

