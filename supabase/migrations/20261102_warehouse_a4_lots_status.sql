-- A4 — Lotes, series, caducidad y estados de stock
-- ----------------------------------------------------------------------------

alter table public.products add column if not exists track_lot boolean not null default false;
alter table public.products add column if not exists track_serial boolean not null default false;
alter table public.products add column if not exists track_expiry boolean not null default false;
alter table public.products add column if not exists issue_strategy text
  check (issue_strategy is null or issue_strategy in ('none','fifo','fefo'))
  default 'none';
alter table public.products add column if not exists max_stock numeric;

alter table public.warehouse_document_lines
  add column if not exists expires_on date,
  add column if not exists stock_status text
    check (stock_status is null or stock_status in ('available','quality','blocked','reserved'));

alter table public.movements
  add column if not exists lot_text text,
  add column if not exists serial_text text,
  add column if not exists expires_on date,
  add column if not exists stock_status text
    check (stock_status is null or stock_status in ('available','quality','blocked','reserved'));

alter table public.stock_balances
  add column if not exists lot_text text,
  add column if not exists expires_on date,
  add column if not exists stock_status text not null default 'available'
    check (stock_status in ('available','quality','blocked','reserved'));

-- Dimensiones ampliadas de saldo (producto+almacén+ubicación+lote+estado)
drop index if exists public.idx_stock_balances_dims;
create unique index if not exists idx_stock_balances_dims_v2
  on public.stock_balances (
    user_id,
    product_id,
    warehouse_id,
    (coalesce(location_id, -1)),
    (coalesce(lot_text, '')),
    (coalesce(stock_status, 'available'))
  );

create table if not exists public.product_serials (
  id bigint generated by default as identity primary key,
  user_id uuid not null default public.get_current_business_id() references auth.users(id),
  product_id bigint not null references public.products(id) on delete cascade,
  serial_number text not null,
  status text not null default 'in_stock'
    check (status in ('in_stock','sold','blocked','disposed')),
  warehouse_id bigint references public.warehouses(id),
  location_id bigint references public.warehouse_locations(id),
  created_at timestamptz not null default now(),
  unique (user_id, product_id, serial_number)
);

alter table public.product_serials enable row level security;

drop policy if exists "product_serials_select" on public.product_serials;
create policy "product_serials_select" on public.product_serials for select to authenticated
  using (public.has_permission_secure(user_id, 'warehouse.view'));

grant select on public.product_serials to authenticated;

-- Sugerir lote FEFO/FIFO para salida
create or replace function public.suggest_issue_lot(p_product_id bigint, p_qty numeric default 1)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_business uuid := public.get_current_business_id();
  v_strategy text;
  v_row record;
begin
  select coalesce(issue_strategy, 'none') into v_strategy
  from public.products
  where id = p_product_id and user_id = v_business;

  if v_strategy is null or v_strategy = 'none' then
    return jsonb_build_object('strategy', 'none');
  end if;

  if v_strategy = 'fefo' then
    select lot_text, expires_on, qty, location_id, warehouse_id
      into v_row
    from public.stock_balances
    where user_id = v_business
      and product_id = p_product_id
      and qty >= p_qty
      and stock_status = 'available'
      and lot_text is not null
    order by expires_on nulls last, updated_at
    limit 1;
  else
    select lot_text, expires_on, qty, location_id, warehouse_id
      into v_row
    from public.stock_balances
    where user_id = v_business
      and product_id = p_product_id
      and qty >= p_qty
      and stock_status = 'available'
      and lot_text is not null
    order by updated_at
    limit 1;
  end if;

  if not found then
    return jsonb_build_object('strategy', v_strategy, 'found', false);
  end if;

  return jsonb_build_object(
    'strategy', v_strategy,
    'found', true,
    'lot_text', v_row.lot_text,
    'expires_on', v_row.expires_on,
    'qty_available', v_row.qty,
    'location_id', v_row.location_id,
    'warehouse_id', v_row.warehouse_id
  );
end;
$$;

revoke all on function public.suggest_issue_lot(bigint, numeric) from public;
grant execute on function public.suggest_issue_lot(bigint, numeric) to authenticated;
