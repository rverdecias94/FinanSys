-- A5 — WMS ligero: reservas, tareas, KPIs básicos
-- ----------------------------------------------------------------------------

create table if not exists public.stock_reservations (
  id bigint generated by default as identity primary key,
  user_id uuid not null default public.get_current_business_id() references auth.users(id),
  product_id bigint not null references public.products(id) on delete cascade,
  qty numeric not null check (qty > 0),
  status text not null default 'active'
    check (status in ('active','released','consumed','cancelled')),
  source_ref text,
  notes text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  released_at timestamptz
);

create index if not exists idx_stock_reservations_product
  on public.stock_reservations (user_id, product_id) where status = 'active';

alter table public.stock_reservations enable row level security;

drop policy if exists "stock_reservations_select" on public.stock_reservations;
drop policy if exists "stock_reservations_insert" on public.stock_reservations;
drop policy if exists "stock_reservations_update" on public.stock_reservations;

create policy "stock_reservations_select" on public.stock_reservations for select to authenticated
  using (public.has_permission_secure(user_id, 'warehouse.view'));
create policy "stock_reservations_insert" on public.stock_reservations for insert to authenticated
  with check (user_id = public.get_current_business_id() and public.has_permission_secure(user_id, 'warehouse.move'));
create policy "stock_reservations_update" on public.stock_reservations for update to authenticated
  using (public.has_permission_secure(user_id, 'warehouse.move'))
  with check (user_id = public.get_current_business_id() and public.has_permission_secure(user_id, 'warehouse.move'));

grant select, insert, update on public.stock_reservations to authenticated;

create table if not exists public.warehouse_tasks (
  id bigint generated by default as identity primary key,
  user_id uuid not null default public.get_current_business_id() references auth.users(id),
  task_type text not null check (task_type in ('putaway','pick','replenish','count','transfer')),
  status text not null default 'open'
    check (status in ('open','in_progress','done','cancelled')),
  priority text not null default 'normal' check (priority in ('high','normal','low')),
  product_id bigint references public.products(id),
  qty numeric,
  from_location_id bigint references public.warehouse_locations(id),
  to_location_id bigint references public.warehouse_locations(id),
  document_id bigint references public.warehouse_documents(id),
  assigned_to uuid references auth.users(id),
  notes text,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

create index if not exists idx_warehouse_tasks_open
  on public.warehouse_tasks (user_id, status, priority) where status in ('open','in_progress');

alter table public.warehouse_tasks enable row level security;

drop policy if exists "warehouse_tasks_select" on public.warehouse_tasks;
drop policy if exists "warehouse_tasks_write" on public.warehouse_tasks;
drop policy if exists "warehouse_tasks_update" on public.warehouse_tasks;

create policy "warehouse_tasks_select" on public.warehouse_tasks for select to authenticated
  using (public.has_permission_secure(user_id, 'warehouse.view'));
create policy "warehouse_tasks_write" on public.warehouse_tasks for insert to authenticated
  with check (user_id = public.get_current_business_id() and public.has_permission_secure(user_id, 'warehouse.move'));
create policy "warehouse_tasks_update" on public.warehouse_tasks for update to authenticated
  using (public.has_permission_secure(user_id, 'warehouse.move'))
  with check (user_id = public.get_current_business_id() and public.has_permission_secure(user_id, 'warehouse.move'));

grant select, insert, update on public.warehouse_tasks to authenticated;

-- Disponibilidad = stock físico − reservas activas
create or replace function public.get_product_availability(p_product_id bigint)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_business uuid := public.get_current_business_id();
  v_stock numeric;
  v_reserved numeric;
begin
  select stock into v_stock from public.products
  where id = p_product_id and user_id = v_business;
  if not found then
    raise exception 'Producto no encontrado' using errcode = 'P0002';
  end if;

  select coalesce(sum(qty), 0) into v_reserved
  from public.stock_reservations
  where user_id = v_business and product_id = p_product_id and status = 'active';

  return jsonb_build_object(
    'product_id', p_product_id,
    'physical', v_stock,
    'reserved', v_reserved,
    'available', greatest(v_stock - v_reserved, 0)
  );
end;
$$;

revoke all on function public.get_product_availability(bigint) from public;
grant execute on function public.get_product_availability(bigint) to authenticated;

create or replace function public.reserve_stock(
  p_product_id bigint,
  p_qty numeric,
  p_source_ref text default null,
  p_notes text default null
)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_business uuid := public.get_current_business_id();
  v_avail jsonb;
  v_id bigint;
begin
  if not public.has_permission_secure(v_business, 'warehouse.move') then
    raise exception 'No autorizado' using errcode = '42501';
  end if;
  if p_qty is null or p_qty <= 0 then
    raise exception 'Cantidad inválida' using errcode = '22023';
  end if;

  v_avail := public.get_product_availability(p_product_id);
  if (v_avail->>'available')::numeric < p_qty then
    raise exception 'Stock disponible insuficiente para reservar' using errcode = '23514';
  end if;

  insert into public.stock_reservations (user_id, product_id, qty, source_ref, notes, created_by)
  values (v_business, p_product_id, p_qty, p_source_ref, p_notes, auth.uid())
  returning id into v_id;

  return jsonb_build_object('reservation_id', v_id) || v_avail
    || jsonb_build_object('available', (v_avail->>'available')::numeric - p_qty);
end;
$$;

revoke all on function public.reserve_stock(bigint, numeric, text, text) from public;
grant execute on function public.reserve_stock(bigint, numeric, text, text) to authenticated;

-- KPIs básicos de almacén
create or replace function public.get_warehouse_kpis()
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_business uuid := public.get_current_business_id();
  v_total int;
  v_low int;
  v_out int;
  v_over_max int;
  v_expiring int;
  v_dead int;
  v_open_tasks int;
begin
  if not public.has_permission_secure(v_business, 'warehouse.view') then
    raise exception 'No autorizado' using errcode = '42501';
  end if;

  select count(*) into v_total from public.products where user_id = v_business;
  select count(*) into v_low from public.products
    where user_id = v_business and stock <= coalesce(min_stock, 5) and stock > 0;
  select count(*) into v_out from public.products where user_id = v_business and stock = 0;
  select count(*) into v_over_max from public.products
    where user_id = v_business and max_stock is not null and stock > max_stock;

  select count(distinct product_id) into v_expiring
  from public.stock_balances
  where user_id = v_business
    and expires_on is not null
    and expires_on <= (current_date + 30)
    and qty > 0;

  select count(*) into v_dead
  from public.products p
  where p.user_id = v_business
    and p.stock > 0
    and not exists (
      select 1 from public.movements m
      where m.product_id = p.id and m.user_id = v_business
        and m.created_at >= now() - interval '90 days'
    );

  select count(*) into v_open_tasks
  from public.warehouse_tasks
  where user_id = v_business and status in ('open','in_progress');

  return jsonb_build_object(
    'total_products', v_total,
    'low_stock', v_low,
    'out_of_stock', v_out,
    'over_max', v_over_max,
    'expiring_30d', v_expiring,
    'dead_stock_90d', v_dead,
    'open_tasks', v_open_tasks
  );
end;
$$;

revoke all on function public.get_warehouse_kpis() from public;
grant execute on function public.get_warehouse_kpis() to authenticated;

-- Productos bajo mínimo o sobre máximo (Min-Max / ROP ligero)
create or replace function public.list_reorder_alerts()
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_business uuid := public.get_current_business_id();
begin
  if not public.has_permission_secure(v_business, 'warehouse.view') then
    raise exception 'No autorizado' using errcode = '42501';
  end if;

  return coalesce((
    select jsonb_agg(jsonb_build_object(
      'product_id', p.id,
      'name', p.name,
      'sku', p.sku,
      'stock', p.stock,
      'min_stock', coalesce(p.min_stock, 5),
      'max_stock', p.max_stock,
      'alert', case
        when p.stock <= 0 then 'out'
        when p.stock <= coalesce(p.min_stock, 5) then 'below_min'
        when p.max_stock is not null and p.stock > p.max_stock then 'above_max'
        else 'ok'
      end
    ) order by p.name)
    from public.products p
    where p.user_id = v_business
      and (
        p.stock <= coalesce(p.min_stock, 5)
        or (p.max_stock is not null and p.stock > p.max_stock)
      )
  ), '[]'::jsonb);
end;
$$;

revoke all on function public.list_reorder_alerts() from public;
grant execute on function public.list_reorder_alerts() to authenticated;
