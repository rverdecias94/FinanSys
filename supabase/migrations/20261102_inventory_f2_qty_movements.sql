-- Inventario F2 — Cantidad tipada + movimientos ligeros (sin edición ciega)
-- ----------------------------------------------------------------------------

alter table public.inventory_items add column if not exists qty numeric;
alter table public.inventory_items add column if not exists uom text;
alter table public.inventory_items add column if not exists status text;
alter table public.inventory_items add column if not exists location text;
alter table public.inventory_items add column if not exists custodian text;
alter table public.inventory_items add column if not exists serial_number text;

create unique index if not exists idx_inventory_items_serial_unique
  on public.inventory_items (user_id, serial_number)
  where serial_number is not null and length(trim(serial_number)) > 0;

create table if not exists public.inventory_item_movements (
  id bigint generated by default as identity primary key,
  user_id uuid not null default public.get_current_business_id() references auth.users(id),
  item_id bigint not null references public.inventory_items(id) on delete cascade,
  qty_delta numeric not null,
  reason text not null,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create index if not exists idx_inventory_item_movements_item
  on public.inventory_item_movements (item_id, created_at desc);

alter table public.inventory_item_movements enable row level security;

drop policy if exists "inventory_item_movements_select" on public.inventory_item_movements;
drop policy if exists "inventory_item_movements_insert" on public.inventory_item_movements;

create policy "inventory_item_movements_select" on public.inventory_item_movements
  for select to authenticated
  using (public.has_permission_secure(user_id, 'inventory.view'));

create policy "inventory_item_movements_insert" on public.inventory_item_movements
  for insert to authenticated
  with check (
    user_id = public.get_current_business_id()
    and public.has_permission_secure(user_id, 'inventory.edit')
  );

grant select, insert on public.inventory_item_movements to authenticated;

-- Backfill best-effort desde values JSONB
update public.inventory_items i
set
  qty = coalesce(
    i.qty,
    nullif(i.values->>'Cantidad','')::numeric,
    nullif(i.values->>'cantidad','')::numeric
  ),
  location = coalesce(i.location, nullif(i.values->>'Ubicación',''), nullif(i.values->>'Ubicacion','')),
  custodian = coalesce(i.custodian, nullif(i.values->>'Custodio','')),
  serial_number = coalesce(i.serial_number, nullif(i.values->>'Serie',''), nullif(i.values->>'Número de serie','')),
  status = coalesce(i.status, nullif(i.values->>'Estado',''))
where i.qty is null
   or i.location is null
   or i.custodian is null
   or i.serial_number is null
   or i.status is null;

create or replace function public.adjust_inventory_item_qty(
  p_item_id bigint,
  p_qty_delta numeric,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_business uuid := public.get_current_business_id();
  v_item public.inventory_items%rowtype;
  v_area public.inventory_areas%rowtype;
  v_new_qty numeric;
  v_values jsonb;
begin
  if not public.has_permission_secure(v_business, 'inventory.edit') then
    raise exception 'No autorizado: requiere inventory.edit' using errcode = '42501';
  end if;
  if p_qty_delta is null or p_qty_delta = 0 then
    raise exception 'El ajuste no puede ser cero' using errcode = '22023';
  end if;
  if p_reason is null or length(trim(p_reason)) < 2 then
    raise exception 'El motivo es obligatorio' using errcode = '22023';
  end if;

  select * into v_item from public.inventory_items
  where id = p_item_id and user_id = v_business for update;
  if not found then
    raise exception 'Ítem no encontrado' using errcode = 'P0002';
  end if;

  select * into v_area from public.inventory_areas where id = v_item.area_id and user_id = v_business;
  if coalesce(v_area.plan_locked, false) then
    raise exception 'Área bloqueada por tu plan' using errcode = '53400';
  end if;
  if v_area.domain_type in ('fixed_asset','tool') then
    raise exception 'Los activos no ajustan cantidad; usa eventos de ciclo de vida' using errcode = '22023';
  end if;

  v_new_qty := coalesce(v_item.qty, 0) + p_qty_delta;
  if v_new_qty < 0 then
    raise exception 'La cantidad no puede quedar negativa' using errcode = '23514';
  end if;

  v_values := coalesce(v_item.values, '{}'::jsonb);
  if v_values ? 'Cantidad' then
    v_values := jsonb_set(v_values, '{Cantidad}', to_jsonb(v_new_qty));
  elsif v_values ? 'cantidad' then
    v_values := jsonb_set(v_values, '{cantidad}', to_jsonb(v_new_qty));
  else
    v_values := v_values || jsonb_build_object('Cantidad', v_new_qty);
  end if;

  update public.inventory_items
    set qty = v_new_qty, values = v_values, updated_at = now()
  where id = p_item_id;

  insert into public.inventory_item_movements (user_id, item_id, qty_delta, reason, created_by)
  values (v_business, p_item_id, p_qty_delta, trim(p_reason), auth.uid());

  return jsonb_build_object(
    'item_id', p_item_id,
    'qty', v_new_qty,
    'qty_delta', p_qty_delta
  );
end;
$$;

revoke all on function public.adjust_inventory_item_qty(bigint, numeric, text) from public;
grant execute on function public.adjust_inventory_item_qty(bigint, numeric, text) to authenticated;

-- Al crear/actualizar ítem, sincronizar columnas tipadas desde values + bloquear qty absurda en activos
create or replace function public.sync_inventory_item_canonical()
returns trigger
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_domain text;
begin
  select domain_type into v_domain from public.inventory_areas where id = new.area_id;

  new.location := coalesce(
    nullif(new.location, ''),
    nullif(new.values->>'Ubicación',''),
    nullif(new.values->>'Ubicacion','')
  );
  new.custodian := coalesce(nullif(new.custodian,''), nullif(new.values->>'Custodio',''));
  new.serial_number := coalesce(
    nullif(new.serial_number,''),
    nullif(new.values->>'Serie',''),
    nullif(new.values->>'Número de serie','')
  );
  new.status := coalesce(nullif(new.status,''), nullif(new.values->>'Estado',''));
  new.uom := coalesce(nullif(new.uom,''), nullif(new.values->>'Unidad',''));

  if v_domain in ('fixed_asset','tool') then
    new.qty := 1;
  else
    begin
      new.qty := coalesce(
        new.qty,
        nullif(new.values->>'Cantidad','')::numeric,
        nullif(new.values->>'cantidad','')::numeric
      );
    exception when others then
      new.qty := coalesce(new.qty, 0);
    end;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_sync_inventory_item_canonical on public.inventory_items;
create trigger trg_sync_inventory_item_canonical
  before insert or update of values, qty, location, custodian, serial_number, status, uom
  on public.inventory_items
  for each row execute function public.sync_inventory_item_canonical();
